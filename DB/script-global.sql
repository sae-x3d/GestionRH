CREATE VIEW public.v_employe_post_depart AS
 SELECT e.id_emp,
    e.nom_emp,
    p.nom_poste,
    d.nom_dept,
    e.salaire_emp,
    e.date_embauche
   FROM ((public.emp e
     JOIN public.poste p ON ((e.id_poste = p.id_poste)))
     JOIN public.departement d ON ((e.id_dept = d.id_dept)))
  WHERE (e.date_depart IS NULL)
  ORDER BY e.id_emp;


