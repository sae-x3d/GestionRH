 SELECT s.libelle_status,
    count(d.id_demande) AS nombre_demandes
   FROM (public.demande_status s
     LEFT JOIN public.demande d ON ((s.id_demande_status = d.id_demande_status)))
  GROUP BY s.id_demande_status, s.libelle_status
  ORDER BY s.id_demande_status;


