--
-- Name: v_demandes_recrutement; Type: VIEW; Schema: public; Owner: -
--

CREATE VIEW public.v_demandes_recrutement AS
 SELECT dem.id_demande,
    p.nom_poste,
    d.nom_dept,
    u.username AS demandeur,
    m.libelle AS motif,
    dem.budget,
    s.libelle_status AS statut,
    dem.date_creation
   FROM (((((public.demande dem
     JOIN public.poste p ON ((dem.id_poste = p.id_poste)))
     JOIN public.departement d ON ((dem.id_dept = d.id_dept)))
     JOIN public.utilisateur u ON ((dem.id_demandeur = u.id_user)))
     JOIN public.motif m ON ((dem.id_motif = m.id_motif)))
     JOIN public.demande_status s ON ((dem.id_demande_status = s.id_demande_status)))
  ORDER BY dem.date_creation DESC;


